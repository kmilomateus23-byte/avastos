class DomainError(Exception):
    """Error de negocio. `mensaje_ui` es el texto que vería el usuario en pantalla."""

    def __init__(self, message: str, mensaje_ui: str | None = None):
        super().__init__(message)
        self.message = message
        self.mensaje_ui = mensaje_ui or message


class InvalidSupplierError(DomainError): ...
class SupplierHasActiveOrdersError(DomainError): ...
class InvalidQuotationError(DomainError): ...
class DuplicateQuotationError(DomainError): ...
class InvalidProductError(DomainError): ...
class InsufficientStockError(DomainError): ...
class OrderError(DomainError): ...
class AuthError(DomainError): ...
